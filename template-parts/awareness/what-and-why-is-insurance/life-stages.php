<script>
// Attach click listeners to cards
document.querySelectorAll('.ls-card').forEach(card => {
    card.addEventListener('click', function() {
        const stage = this.getAttribute('data-stage');
        showStageDetail(stage);
    });
});

// NEW: Auto-open detail card if a ?stage=xxx param is present in the URL
(function openStageFromURL() {
    const params = new URLSearchParams(window.location.search);
    const stageParam = params.get('stage');

    if (stageParam) {
        const target = document.getElementById('detail-' + stageParam);
        if (target) {
            showStageDetail(stageParam);
        }
    }
})();

function showStageDetail(stageId) {
    // Hide all stage detail cards
    document.querySelectorAll('.ls-detail-card').forEach(card => {
        card.classList.remove('active');
    });

    // Show requested stage card
    const target = document.getElementById('detail-' + stageId);
    if (target) {
        target.classList.add('active');
        document.getElementById('lsDetailsContainer').style.display = 'block';
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
}

function closeStageDetail() {
    document.getElementById('lsDetailsContainer').style.display = 'none';
    document.querySelectorAll('.ls-detail-card').forEach(card => {
        card.classList.remove('active');
    });
}

