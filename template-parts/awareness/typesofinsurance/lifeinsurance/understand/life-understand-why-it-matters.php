<script>
document.addEventListener('DOMContentLoaded', function() {
    const grid = document.getElementById('reasonsGrid');
    if (!grid) return;

    const buttons = grid.querySelectorAll('.toggle-details-btn');

    buttons.forEach(button => {
        button.addEventListener('click', function() {
            const card = this.closest('.case-for-cover__full-bg-card');
            const previewText = card.querySelector('.preview-text');
            const fullText = card.querySelector('.full-text');

            const isExpanded = card.classList.toggle('is-expanded');

            if (isExpanded) {
                previewText.style.display = 'none';
                fullText.style.display = 'block';
                this.textContent = 'Hide Details';
            } else {
                previewText.style.display = 'block';
                fullText.style.display = 'none';
                this.textContent = this.textContent.replace('Hide Details', ' Details');
            }
        });
    });
});
</script>