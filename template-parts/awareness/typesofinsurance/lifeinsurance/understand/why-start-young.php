<script>
document.addEventListener('DOMContentLoaded', function() {
    function initColumnTabs(columnId) {
        const column = document.getElementById(columnId);
        if (!column) return;

        const tabs = column.querySelectorAll('.char-infographic__tab');
        const panes = column.querySelectorAll('.char-infographic__pane');

        tabs.forEach(tab => {
            tab.addEventListener('click', function() {
                const targetAge = this.getAttribute('data-age');
                const targetStage = this.getAttribute('data-stage');
                const targetValue = targetAge || targetStage;

                tabs.forEach(t => t.classList.remove('is-active'));
                this.classList.add('is-active');

                panes.forEach(pane => {
                    const paneAge = pane.getAttribute('data-age');
                    const paneStage = pane.getAttribute('data-stage');
                    const paneValue = paneAge || paneStage;

                    if (paneValue === targetValue) {
                        pane.classList.add('is-active');
                    } else {
                        pane.classList.remove('is-active');
                    }
                });
            });
        });
    }

    initColumnTabs('leftColumnGroup');
    initColumnTabs('rightColumnGroup');
});
</script>