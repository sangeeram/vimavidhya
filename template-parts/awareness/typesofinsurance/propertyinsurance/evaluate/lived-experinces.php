                    washer-dryer, a full home office setup. The total value
                    of everything they owned inside that flat:
                    ₹3.5 lakhs.
                </p>


                <p>
                    One morning, a short circuit in the building's common
                    meter box triggered a fire that spread to three flats.
                    Their washing machine and entire home office setup
                    were destroyed. Sandeep called the landlord — who did
                    have a policy. But that policy covered only the
                    building's <strong>insured structure</strong>:
                    the walls, roof, and floors. It did not — and legally
                    cannot — extend to a tenant's personal belongings.
                </p>


                <p>
                    Sandeep and Prathima had no policy of their own.
                    There was no <strong>contents cover</strong> to replace
                    their electronics. No <strong>fire peril</strong>
                    protection on their belongings. They replaced what
                    they could on a credit card and spent the following
                    year repaying the debt.
                </p>


                <p>
                    Later, they discovered that a
                    <strong>tenant's contents policy</strong> covering
                    ₹3.5 lakhs of belongings would have cost them
                    approximately ₹3,000–₹4,500 a year in
                    <strong>premium</strong> — less than ₹400 a month.
                    As they lived in a rented home, they had full
                    <strong>insurable interest</strong> in everything
                    they brought into it. The landlord's insurance was
                    never designed to cover Sandeep and Prathima.
                    Only they could do that — and they hadn't.
                </p>

